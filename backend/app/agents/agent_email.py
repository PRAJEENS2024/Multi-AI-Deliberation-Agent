# EXPORT FORMATS: JSON & Markdown builders (for Export Button feature)
# ═══════════════════════════════════════════════════════════════════════════════

def build_json_report(
    prompt: str,
    final_answer: str,
    report_data: dict,
    confidence_score: int,
    debate_turns: list = None,
    consensus_claims: list = None,
    disputed_claims: list = None,
) -> str:
    """Build a structured JSON report for export."""
    report = {
        "report_metadata": {
            "generated_by": "AI Jury - 7-Agent Deliberation Pipeline",
            "generated_at": datetime.now().isoformat(),
            "confidence_score": confidence_score,
            "agent_count": 7,
        },
        "query": prompt,
        "executive_summary": report_data.get("executive_summary", ""),
        "key_findings": report_data.get("key_findings", []),
        "recommendations": report_data.get("recommendations", []),
        "sections": report_data.get("sections", []),
        "final_answer": final_answer,
        "claim_analysis": {
            "consensus_claims": consensus_claims or [],
            "disputed_claims": disputed_claims or [],
        },
        "agent_debate_turns": debate_turns or [],
    }
    return json.dumps(report, indent=2, default=str)


def build_markdown_report(
    prompt: str,
    final_answer: str,
    report_data: dict,
    confidence_score: int,
    debate_turns: list = None,
    consensus_claims: list = None,
    disputed_claims: list = None,
) -> str:
    """Build a formatted Markdown report for export."""
    lines = []
    lines.append("# AI Jury Report\n")
    lines.append(f"**Generated:** {datetime.now().strftime('%B %d, %Y at %H:%M UTC')}  \n")
    lines.append(f"**Confidence Score:** {confidence_score}%  \n")
    lines.append(f"**Pipeline:** 7-Agent Deliberation\n")
    lines.append("---\n")

    lines.append(f"## Query\n\n> {prompt}\n")
    lines.append("---\n")

    exec_summary = report_data.get("executive_summary", "")
    if exec_summary:
        lines.append(f"## Executive Summary\n\n{exec_summary}\n")
        lines.append("---\n")

    lines.append("## Final Synthesized Answer\n\n")
    lines.append(final_answer)
    lines.append("\n---\n")

    findings = report_data.get("key_findings", [])
    if findings:
        lines.append("## Key Findings\n")
        for f in findings:
            lines.append(f"- {f}")
        lines.append("\n---\n")

    recs = report_data.get("recommendations", [])
    if recs:
        lines.append("## Recommendations\n")
        for r in recs:
            lines.append(f"- {r}")
        lines.append("\n---\n")

    if consensus_claims:
        lines.append("## Consensus Claims\n")
        for c in consensus_claims:
            claim_text = c.get("claim", c) if isinstance(c, dict) else str(c)
            lines.append(f"- {claim_text}")
        lines.append("\n")

    if disputed_claims:
        lines.append("## Disputed Claims\n")
        for d in disputed_claims:
            claim_text = d.get("claim", d) if isinstance(d, dict) else str(d)
            evidence = d.get("evidence", "") if isinstance(d, dict) else ""
            lines.append(f"- {claim_text}")
            if evidence:
                lines.append(f"  - *Evidence: {evidence[:200]}*")
        lines.append("\n")

    if debate_turns:
        lines.append("## Agent Deliberation Transcript\n")
        for turn in debate_turns:
            t = turn if isinstance(turn, dict) else turn.dict() if hasattr(turn, 'dict') else str(turn)
            speaker = t.get("speaker_persona", "Agent")
            target = t.get("target_persona", "")
            arg = t.get("argument", "")
            header = f"### Turn {t.get('turn_number', '')}: {speaker}"
            if target:
                header += f" -> {target}"
            lines.append(header)
            lines.append(f"\n{arg}\n")

    lines.append("\n---\n")
    lines.append(f"*Generated by AI Jury 7-Agent LangGraph Pipeline*")

    return "\n".join(lines)


